"""Stage 3 (Document): the documentation agent drafts SS1/23-aligned model documentation with
confidence levels and unknowns; deterministic checks compare it against the fitted model.
"""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

from factory import discover, model_card, scanner
from factory.agents import documentation as doc_agent
from factory.agents.documentation import SECTIONS

STAGE = "document"
SECTION_TITLES = {
    "purpose_and_use": ("Purpose and intended use", "P3"),
    "data": ("Data", "P3"),
    "methodology": ("Methodology", "P3"),
    "implementation": ("Implementation", "P3"),
    "performance": ("Performance (reference outputs)", "P4"),
    "monitoring_and_governance": ("Monitoring and governance", "P2, P5"),
}


def _norm(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.lower().removeprefix("woe_"))


def model_terms(root: Path, model_id: str) -> list[str] | None:
    """Input variables actually used by the fitted reference model, or None if unknown."""
    ref = root / "artifacts" / "reference" / model_id
    coef = ref / "coefficients.csv"
    if coef.exists():
        terms = set()
        with coef.open() as f:
            for row in csv.DictReader(f):
                t = re.sub(r"\[T\..*\]$", "", row["term"])
                m = re.match(r"^\w+\(\s*([^,)]+)", t)
                t = (m.group(1) if m else t).strip().removeprefix("woe_")
                if t.lower() not in ("intercept", "(intercept)"):
                    terms.add(t)
        return sorted(terms)
    metrics = ref / "metrics.json"
    if metrics.exists():
        m = json.loads(metrics.read_text())
        for key in ("selected_variables", "features"):
            if isinstance(m.get(key), list):
                return list(m[key])
    return None


def _expand(name: str) -> list[str]:
    m = re.match(r"^([A-Za-z_]+)(\d+)\s*(?:-|–|\.\.|to)\s*\1?(\d+)$", name.strip())
    if m:
        return [f"{m.group(1)}{i}" for i in range(int(m.group(2)), int(m.group(3)) + 1)]
    return [name]


def coverage(terms: list[str] | None, variables: list[dict]) -> dict:
    """Compare documented input variables with the variables the fitted model uses."""
    if terms is None:
        return {"available": False, "note": "no reference outputs (model not executed)"}
    documented = [_norm(x) for v in variables if v["role"] in ("input", "offset")
                  for x in _expand(v["name"])]

    def found(term: str) -> bool:
        t = _norm(term)
        return any(d == t or d.startswith(t) or d.endswith(t) for d in documented)

    missing = [t for t in terms if not found(t)]
    model_norm = {_norm(t) for t in terms}
    extra = [v["name"] for v in variables if v["role"] == "input"
             and not any(_norm(x) in model_norm or any(_norm(x).startswith(m) or
                                                        _norm(x).endswith(m) for m in model_norm)
                         for x in _expand(v["name"]))]
    return {"available": True, "model_terms": len(terms), "documented": len(terms) - len(missing),
            "missing": missing, "extra": extra}


def assess(doc: dict, cov: dict) -> list[str]:
    gaps = []
    for key in SECTIONS:
        s = doc["sections"][key]
        if s["text"] is None:
            gaps.append(f"Section '{SECTION_TITLES[key][0]}' not described.")
        elif s["confidence"] == "low":
            gaps.append(f"Section '{SECTION_TITLES[key][0]}' is low confidence"
                        f"{' (' + s['flag'] + ')' if s['flag'] else ''}.")
    if cov.get("missing"):
        gaps.append(f"Model uses variables not documented: {', '.join(cov['missing'])}.")
    if cov.get("extra"):
        gaps.append(f"Documented as inputs but not in the fitted model: {', '.join(cov['extra'])}.")
    ungrounded = [s for k in ("assumptions", "limitations") for s in doc[k] if not s["grounded"]]
    if ungrounded:
        gaps.append(f"{len(ungrounded)} assumption(s)/limitation(s) inferred without a supporting "
                    "quote; reviewer judgement needed.")
    if doc["rejected"]:
        gaps.append(f"{len(doc['rejected'])} agent claim(s) dropped by the evidence check.")
    return gaps


def _md_cell(x) -> str:
    return str(x if x is not None else "").replace("|", "\\|").replace("\n", " ")


def render_markdown(card: dict) -> str:
    inv, doc = card["inventory"], card["documentation"]
    ev = inv.get("evidence", {})
    llm = doc["llm"]
    ref = inv.get("model_ref") or card["model_id"]
    title = card["name"] if ref in card["name"] else f"{card['name']} ({ref})"
    out = [f"# {title}: model documentation",
           "",
           f"> **DRAFT, generated by the documentation agent; status: {doc['status']}.** "
           "Section references (P1-P5) are the PRA SS1/23 principles the content supports. "
           "Confidence: high = stated in code/outputs, medium = clear from code, low = inferred "
           "or unsupported.",
           "",
           f"Generated {doc['generated_at']} by `{llm['model']}` from card version "
           f"{card['card_version']}. Sources: {', '.join(f'`{s}`' for s in doc['sources'])}.",
           "", "## 1. Identification and classification (P1)", "",
           "| Field | Value | Evidence |", "|---|---|---|"]
    for label, key in (("Model reference", "model_ref"), ("Owner", "owner"),
                       ("Purpose", "purpose"), ("Model type", "model_type"),
                       ("Risk tier", "risk_tier"), ("Last validation", "last_validation_date"),
                       ("Documentation status", "documentation_status")):
        out.append(f"| {label} | {_md_cell(inv.get(key) or 'unknown')} | "
                   f"{_md_cell(ev.get(key, {}).get('evidence'))} |")
    out += [f"| Language / files | {card['language']} | "
            f"{_md_cell(', '.join(card['source_files']))} |",
            f"| Data sources | {_md_cell(', '.join(inv.get('data_sources', [])))} | scanner |", ""]
    if ev.get("risk_tier", {}).get("rationale"):
        out += [f"Risk tier rationale: {ev['risk_tier']['rationale']}", ""]

    n = 2
    for key in SECTIONS[:3]:
        out += _section(n, key, doc["sections"][key])
        n += 1
    out += [f"## {n}. Variables (P3)", "", "| Variable | Role | Description | Transformation |",
            "|---|---|---|---|"]
    out += [f"| `{_md_cell(v['name'])}` | {v['role']} | {_md_cell(v['description'])} | "
            f"{_md_cell(v['transformation'])} |" for v in doc["variables"]]
    cov = doc["coverage"]
    out += ["", ("Coverage check against the fitted model: "
                 + (f"{cov['documented']}/{cov['model_terms']} model variables documented"
                    + (f"; missing: {', '.join(cov['missing'])}" if cov["missing"] else "")
                    + (f"; not in model: {', '.join(cov['extra'])}" if cov["extra"] else "")
                    if cov["available"] else cov["note"])) + ".", ""]
    n += 1
    out += [f"## {n}. Transformations (P3)", ""]
    out += [f"{i}. **{_md_cell(t['step'])}**: {t['description']}  \n   Evidence: "
            f"`{_md_cell(t['evidence'])}` ({t['source']})"
            for i, t in enumerate(doc["transformations"], 1)]
    out.append("")
    n += 1
    for title, key in (("Assumptions", "assumptions"), ("Limitations", "limitations")):
        out += [f"## {n}. {title} (P3, P5)", ""]
        out += [f"- [{s['confidence']}] {s['text']}" + (
            f"  \n  Evidence: `{_md_cell(s['evidence'])}` ({s['source']})" if s["grounded"]
            else "  \n  *Inferred; no supporting quote. Reviewer judgement needed.*")
            for s in doc[key]] or ["- none stated"]
        out.append("")
        n += 1
    for key in SECTIONS[3:]:
        out += _section(n, key, doc["sections"][key])
        n += 1
    out += [f"## {n}. Gaps and unknowns", "", "**Open gaps (Stage 2 inventory and Stage 3 checks)**",
            ""]
    out += [f"- {g}" for g in card.get("gaps", []) + doc["gaps"]] or ["- none"]
    out += ["", "**Unknowns stated by the agent**", ""]
    out += [f"- {u}" for u in doc["unknowns"]] or ["- none"]
    if doc["rejected"]:
        out += ["", "**Agent claims dropped by the evidence check**", ""]
        out += [f"- {r['item']}: {r['problem']}" for r in doc["rejected"]]
    return "\n".join(out) + "\n"


def _section(n: int, key: str, s: dict) -> list[str]:
    title, principle = SECTION_TITLES[key]
    lines = [f"## {n}. {title} ({principle})", "",
             f"*Confidence: {s['confidence']}{' (' + s['flag'] + ')' if s['flag'] else ''}*", "",
             s["text"] or "_Not described._", ""]
    if s["evidence"]:
        lines += ["Evidence:"] + [f"- `{_md_cell(e['quote'])}` ({e['source']})"
                                  for e in s["evidence"]] + [""]
    return lines


def gather_texts(card: dict, root: Path, model_dir: Path, dcfg: dict) -> dict[str, str]:
    cap = dcfg["max_chars_per_file"]
    disc = card.get("discovery") or scanner.scan_model(model_dir, root)
    paths = [f["path"] for f in disc["files"]] + [d["path"] for d in disc["doc_files"] if d["chars"]]
    texts = {p: (root / p).read_text(errors="replace")[:cap] for p in paths}
    ref = root / "artifacts" / "reference" / card["model_id"]
    for name in dcfg["reference_files"]:
        if (ref / name).exists():
            texts[str((ref / name).relative_to(root))] = (ref / name).read_text()[:cap]
    return texts


def run_stage(card: dict, ctx) -> dict:
    cfg, dcfg = ctx.cfg, ctx.cfg["document"]
    root = ctx.model_dir.parent.parent
    texts = gather_texts(card, root, ctx.model_dir, dcfg)
    inv, disc = card["inventory"], card.get("discovery", {})
    context = {"name": card["name"],
               **{k: inv.get(k) for k in ("model_ref", "owner", "purpose", "model_type",
                                           "risk_tier", "last_validation_date",
                                           "documentation_status")},
               **{k: disc.get(k) for k in ("languages", "libraries", "inputs", "outputs",
                                           "methods", "seeds")},
               "documentation_contradictions": [f["issue"] for f in
                                                disc.get("documentation_findings", [])],
               "inventory_gaps": card.get("gaps", [])}
    feedback = discover.reviewer_feedback(cfg["paths"]["audit"], card["model_id"],
                                          card["stages"][STAGE]["completed_at"], stage=STAGE)
    doc = doc_agent.run(ctx.llm, card["model_id"], context, texts, dcfg, feedback)
    doc["coverage"] = coverage(model_terms(root, card["model_id"]), doc["variables"])
    doc["gaps"] = assess(doc, doc["coverage"])
    out_dir = Path(cfg["paths"]["model_docs"])
    out_dir.mkdir(parents=True, exist_ok=True)
    doc_path = out_dir / f"{card['model_id']}.md"
    doc.update(generated_at=model_card.now_iso(), sources=list(texts), status="pending Gate 2",
               doc_path=str(doc_path), reviewer_feedback_used=feedback)
    card["documentation"] = doc
    model_card.validate(card)
    doc_path.write_text(render_markdown(card))

    conf = {k: doc["sections"][k]["confidence"] for k in SECTIONS}
    cov, llm = doc["coverage"], doc["llm"]
    summary = "\n".join([
        f"Draft documentation: {doc_path}",
        "Section confidence: " + ", ".join(f"{SECTION_TITLES[k][0].split(' (')[0]} {v}"
                                           for k, v in conf.items()),
        f"{len(doc['variables'])} variables, {len(doc['transformations'])} transformations, "
        f"{len(doc['assumptions'])} assumptions, {len(doc['limitations'])} limitations, "
        f"{len(doc['unknowns'])} unknowns",
        "Coverage vs fitted model: " + (f"{cov['documented']}/{cov['model_terms']} variables"
                                        if cov["available"] else cov["note"]),
        f"Gaps ({len(doc['gaps'])}):", *[f"- {g}" for g in doc["gaps"]],
        f"LLM: {llm['model']}, {llm['input_tokens'] + llm['output_tokens']} tokens, "
        f"${llm['cost_usd']:.4f}{' (cached)' if llm['cached'] else ''}",
    ])
    return {"summary": summary}
